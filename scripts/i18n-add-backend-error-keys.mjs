for (const loc of ["en", "de", "fr", "ar"]) {
  const path = join(localesDir, `${loc}.json`);
  const catalog = JSON.parse(readFileSync(path, "utf8"));
  let n = 0;
  for (const [k, v] of Object.entries(keys[loc])) {
    if (catalog[k] !== v) {
      catalog[k] = v;
      n++;
    }
  }
  const sorted = Object.fromEntries(Object.keys(catalog).sort().map((k) => [k, catalog[k]]));
  writeFileSync(path, `${JSON.stringify(sorted, null, 2)}\n`);
  console.log(`${loc}.json: ${n} backend error keys added/updated`);
}
